-- =============================================================================
-- Migración: init_inventory
-- Propósito: catálogo de inventario de demostración (categorías + productos).
-- Modelo de acceso: lectura pública de solo lectura; las escrituras quedan
-- reservadas a `service_role`, al rol propietario (`postgres`) y a la consola SQL.
--
-- Seguridad (RLS): se habilita RLS y solo se crean políticas de SELECT para
-- `anon` y `authenticated`. Al no existir políticas de INSERT/UPDATE/DELETE,
-- esas operaciones se deniegan por defecto para dichos roles.
-- =============================================================================

-- ---------------------------------------------------------------------------
-- Tablas
-- ---------------------------------------------------------------------------
create table if not exists public.categories (
  id   bigint generated by default as identity primary key,
  name text   not null unique
);

comment on table  public.categories      is 'Catálogo de categorías de productos (lectura pública, escritura restringida).';
comment on column public.categories.id   is 'Identificador interno de la categoría.';
comment on column public.categories.name is 'Nombre único de la categoría (ej. Electrónica).';

create table if not exists public.products (
  id          bigint          generated by default as identity primary key,
  name        text            not null,
  description text,
  price       numeric(10, 2)  not null check (price >= 0),
  stock       integer         not null default 0 check (stock >= 0),
  category_id bigint          not null references public.categories (id),
  created_at  timestamptz     not null default now()
);

comment on table  public.products             is 'Productos del inventario de demostración (lectura pública, escritura restringida).';
comment on column public.products.id          is 'Identificador interno del producto.';
comment on column public.products.name        is 'Nombre comercial del producto.';
comment on column public.products.description is 'Descripción opcional del producto; puede ser null.';
comment on column public.products.price       is 'Precio unitario (numeric(10,2)); nunca negativo.';
comment on column public.products.stock       is 'Unidades disponibles; nunca negativo.';
comment on column public.products.category_id is 'FK a public.categories(id).';
comment on column public.products.created_at  is 'Fecha de alta del producto (timestamptz, UTC).';

-- ---------------------------------------------------------------------------
-- Índices
-- ---------------------------------------------------------------------------
create index if not exists products_category_id_idx on public.products (category_id);

-- ---------------------------------------------------------------------------
-- Row Level Security
-- ---------------------------------------------------------------------------
alter table public.categories enable row level security;
alter table public.products   enable row level security;

-- Lectura pública del catálogo (idempotente: se recrea la política).
drop policy if exists "categories_select_public" on public.categories;
create policy "categories_select_public"
  on public.categories
  for select
  to anon, authenticated
  using (true);

drop policy if exists "products_select_public" on public.products;
create policy "products_select_public"
  on public.products
  for select
  to anon, authenticated
  using (true);

-- NO se crean políticas de INSERT/UPDATE/DELETE. Con RLS activo y sin política
-- aplicable, esas operaciones se deniegan por defecto a `anon` y `authenticated`.
-- Las escrituras quedan por tanto reservadas a `service_role` (que omite RLS),
-- al rol propietario de las tablas (`postgres`) y a la consola SQL de Studio.

-- ---------------------------------------------------------------------------
-- Privilegios explícitos y auditables
-- ---------------------------------------------------------------------------
grant usage on schema public to anon, authenticated, service_role;

-- Deja el conjunto de privilegios de escritura en cero para los roles públicos.
-- (Revocar es seguro aunque no existiera la concesión previa.)
revoke all on table public.categories, public.products from anon, authenticated;

-- `anon` y `authenticated`: únicamente SELECT sobre las tablas.
grant select on table public.categories, public.products to anon, authenticated;

-- `service_role`: control total (omite RLS y realiza las escrituras legítimas).
grant all on table public.categories, public.products to service_role;
